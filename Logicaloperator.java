public class Logicaloperator {
    public static void main(String[] args) {
        System.out.println((8>0)&&(9<4));
         System.out.println((8>0)&&(9>4));
         System.out.println(!(3>2));
//          	Logical operator
// 1.	&&      and  = if both are true then it give true if any one is not true it give false
// 2.	||      or   => if any one statement is true it is true
// 3.	!       not  => make the true statement false and false into true

    }
    
}
